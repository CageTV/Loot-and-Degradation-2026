"""Reads the original's _EDQuestScript.SetUpNames and writes plugin/src/EnchantNames.h: for each equipment slot the suffix that goes with the
enchantment at the same index of that slot's _EDEnchant*List form list ("Iron Sword" + " of Fire")."""
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
src = (root / "reference/original-LE-1.31/scripts-source/_edquestscript.psc").read_text(encoding="utf-8", errors="replace").splitlines()

start = next(i for i, l in enumerate(src) if l.startswith("Function SetUpNames"))
end = next(i for i in range(start, len(src)) if src[i].startswith("EndFunction"))

arrays: dict[str, list[str]] = {}
assign = re.compile(r'^\s*(\w+)\[(\d+)\]\s*=\s*(?:"([^"]*)"|(\w+)\[(\d+)\])')
new = re.compile(r'^\s*(\w+)\s*=\s*New String\[(\d+)\]')
for line in src[start:end]:
    m = new.match(line)
    if m:
        arrays[m.group(1)] = [""] * int(m.group(2))
        continue
    m = assign.match(line)
    if not m:
        continue
    name, idx = m.group(1), int(m.group(2))
    if m.group(3) is not None:
        arrays[name][idx] = m.group(3)
    else:
        arrays[name][idx] = arrays[m.group(4)][int(m.group(5))]

order = [("Weapon", "EnchantWeaponName"), ("Head", "EnchantHeadName"), ("Body", "EnchantBodyName"), ("Hand", "EnchantHandName"),
         ("Feet", "EnchantFeetName"), ("Shield", "EnchantShieldName")]
out = ["// Generated by tools/gen_enchant_names.py from the original's _EDQuestScript.SetUpNames (CC BY-NC-SA 4.0, isoku). Do not edit.",
       "#pragma once", "#include <array>", "namespace EnchantNames", "{"]
for label, key in order:
    names = arrays[key]
    last = max(i for i, n in enumerate(names) if n) + 1
    body = ",\n\t\t".join('"%s"' % n.replace('"', '\\"') for n in names[:last])
    out.append("\tinline constexpr std::array<const char*, %d> k%s{\n\t\t%s };" % (last, label, body))
out.append("}")
(root / "plugin/src/EnchantNames.h").write_text("\n".join(out) + "\n", encoding="utf-8")
print({k: sum(1 for n in v if n) for k, v in arrays.items()})
